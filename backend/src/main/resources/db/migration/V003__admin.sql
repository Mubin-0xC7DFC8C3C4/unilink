-- V003 admin (D-030 separate admin_accounts, D-031 TOTP, D-036 recommendations, D-038 alerts)
CREATE TABLE IF NOT EXISTS admin_accounts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, email VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL, role VARCHAR(32) NOT NULL,
  university_id BIGINT UNSIGNED NULL, active TINYINT(1) NOT NULL DEFAULT 1,
  totp_enrolled TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id), UNIQUE KEY uk_admin_email (email), INDEX idx_admin_uni (university_id),
  CONSTRAINT fk_admin_uni FOREIGN KEY (university_id) REFERENCES universities(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS admin_totp_secrets (
  admin_id BIGINT UNSIGNED NOT NULL, secret_encrypted VARCHAR(512) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (admin_id),
  CONSTRAINT fk_totp_admin FOREIGN KEY (admin_id) REFERENCES admin_accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS admin_recovery_codes (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, admin_id BIGINT UNSIGNED NOT NULL,
  code_hash CHAR(64) NOT NULL, used TINYINT(1) NOT NULL DEFAULT 0, used_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id), INDEX idx_rec_admin (admin_id),
  CONSTRAINT fk_rec_admin FOREIGN KEY (admin_id) REFERENCES admin_accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS admin_email_otps (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, admin_id BIGINT UNSIGNED NOT NULL,
  otp_hash CHAR(64) NOT NULL, attempts INT NOT NULL DEFAULT 0, used TINYINT(1) NOT NULL DEFAULT 0,
  expires_at DATETIME(3) NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id), INDEX idx_aotp_admin (admin_id, created_at),
  CONSTRAINT fk_aotp_admin FOREIGN KEY (admin_id) REFERENCES admin_accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS suspension_recommendations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, user_id BIGINT UNSIGNED NOT NULL,
  moderator_id BIGINT UNSIGNED NOT NULL, reason VARCHAR(1024) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING', decided_by BIGINT UNSIGNED NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), decided_at DATETIME(3) NULL,
  PRIMARY KEY (id), INDEX idx_susprec_user (user_id, created_at),
  CONSTRAINT fk_susprec_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_susprec_mod FOREIGN KEY (moderator_id) REFERENCES admin_accounts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS admin_alerts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, admin_id BIGINT UNSIGNED NULL,
  university_id BIGINT UNSIGNED NULL, type VARCHAR(64) NOT NULL,
  target_type VARCHAR(64) NULL, target_id BIGINT UNSIGNED NULL,
  message VARCHAR(1024) NOT NULL, read_flag TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id), INDEX idx_alert_admin (admin_id, created_at),
  UNIQUE KEY uk_alert_once (type, target_type, target_id, admin_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS admin_ip_allowlist (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, cidr VARCHAR(64) NOT NULL, active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id), UNIQUE KEY uk_ip_cidr (cidr)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
